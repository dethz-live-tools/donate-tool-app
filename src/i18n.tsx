// Keys missing in th fall back to the English source text (same key).
export const tFor = (lang: Lang, key: string, vars?: Record<string, string | number>): string => {
  const dict = dictionaries[lang];
  const raw = Object.prototype.hasOwnProperty.call(dict, key) ? dict[key] : key;
  if (!vars) return raw;
  return Object.entries(vars).reduce((acc, [k, v]) => acc.split(`{${k}}`).join(String(v)), raw);
};

interface LangCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
}

const Ctx = createContext<LangCtx>({ lang: "en", setLang: () => {}, t: (k, vars) => tFor("en", k, vars) });

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    try {
      const saved = localStorage.getItem("donate_socket_lang");
      return saved === "th" || saved === "en" ? saved : "en";
    } catch {
      return "en";
    }
  });

  useEffect(() => {
    try {
      localStorage.setItem("donate_socket_lang", lang);
    } catch {}
  }, [lang]);

  const t = (key: string, vars?: Record<string, string | number>) => tFor(lang, key, vars);
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export const useLang = () => useContext(Ctx);
